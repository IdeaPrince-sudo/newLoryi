  sidebarSections
    .map((section) => ({
      ...section,
      items: moduleRegistry.filter(
        (module) =>
          module.category === section.key &&
          (module.module === null || currentUser?.role === 'admin' || currentUser?.modules?.includes(module.module))
      ),
    }))
    .filter((section) => section.items.length > 0);

